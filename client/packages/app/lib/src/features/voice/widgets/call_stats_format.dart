/// How the call stats read: a talk time, a pace and a language name (decision 0113).
library;

/// `45 s`, `12 min`, or `1 h 05 min`.
String formatTalkTime(int ms) {
  final minutes = ms ~/ 60000;
  if (minutes < 1) return '${ms ~/ 1000} s';
  if (minutes < 60) return '$minutes min';
  final rest = (minutes % 60).toString().padLeft(2, '0');
  return '${minutes ~/ 60} h $rest min';
}

/// A pace with no needless decimal: `140`, `6.4`.
String formatPace(double value) => value == value.roundToDouble()
    ? '${value.round()}'
    : value.toStringAsFixed(1);

/// A whisper language code as its English name; the code itself when unknown.
String callStatsLanguageName(String code) {
  if (code == 'other') return 'Other languages';
  return _names[code.toLowerCase()] ?? code;
}

