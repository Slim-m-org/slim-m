NAME = re.compile(r"^(.*) - \(([A-Z]{3})\)\s*$")


def load(argv):
    if len(argv) > 1:
        return json.loads(pathlib.Path(argv[1]).read_text(encoding="utf-8"))
    request = urllib.request.Request(SOURCE, headers={"User-Agent": "colo-table-generator"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def rows(components):
    table = {}
    for component in components:
        match = NAME.match(component.get("name", ""))
        if not match:
            continue
        parts = [p.strip() for p in match.group(1).split(",")]
        country = parts[-1]
        if country not in ISO2:
            sys.exit(f"no ISO code for {country!r}; add it to ISO2")
        table[match.group(2)] = (parts[0], ISO2[country])
    return dict(sorted(table.items()))


def dart_string(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main(argv):
    table = rows(load(argv)["components"])
    lines = [
        "// SPDX-License-Identifier: LicenseRef-PolyForm-Noncommercial-1.0.0",
        "// GENERATED by scripts/gen-cloudflare-colos.py from cloudflarestatus.com; do not edit.",
        "",
        "/// Each Cloudflare data centre code with its city and two-letter country.",
        "const cloudflareColos = <String, (String, String)>{",
    ]
    lines += [f"  '{code}': ({dart_string(city)}, '{cc}')," for code, (city, cc) in table.items()]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(table)} data centres to {OUT}")


if __name__ == "__main__":
    main(sys.argv)
