// Generates src/icons.ts from the Flutter AppIcons table so both clients name icons the same way.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const lucide = require('lucide-react');
const source = readFileSync(
  new URL('../../../client/packages/design_system/lib/src/app_icons.dart', import.meta.url),
  'utf8',
);
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const entries = [];
const missing = [];
for (const m of source.matchAll(/static const IconData (\w+) = LucideIcons\.(\w+?)(\d00)?;/g)) {
  const [, name, flutterName] = m;
  const component = pascal(flutterName);
  if (lucide[component]) entries.push([name, component]);
  else missing.push(`${name} -> ${component}`);
}
if (missing.length) {
  console.error(`no lucide-react icon for:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}
const imports = [...new Set(entries.map(([, c]) => c))].sort();
const out = `// Generated by scripts/gen-icons.mjs from client/packages/design_system/lib/src/app_icons.dart. Do not edit.
import {
${imports.map((c) => `  ${c},`).join('\n')}
} from 'lucide-react';
import type { LucideIcon } from 'lucide-react';

export const appIcons = {
${entries.map(([n, c]) => `  ${n}: ${c},`).join('\n')}
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof appIcons;
`;
writeFileSync(new URL('../src/icons.ts', import.meta.url), out);
console.log(`${entries.length} icons`);
